require('./test-preflight.js');
const assert = require('node:assert/strict');
const fs=require('node:fs');
const { bufferTrack, simplifyTrack } = require('../public/assets/js/safe-zone-geometry.js');
const editor=fs.readFileSync(require('node:path').join(__dirname,'../public/assets/js/safe-zone.js'),'utf8');
const editorPage=fs.readFileSync(require('node:path').join(__dirname,'../public/safe-zone.php'),'utf8');
const p=(x,y)=>({latitude:14.8+y/110540,longitude:121+x/(Math.cos(14.8*Math.PI/180)*111320)});
const area=points=>Math.abs(points.reduce((sum,a,i)=>{const b=points[(i+1)%points.length];return sum+a.longitude*b.latitude-b.longitude*a.latitude;},0)/2);
const straight=bufferTrack([p(0,0),p(100,0)],15);assert.equal(straight.length,4);assert.ok(area(straight)>0);assert.ok(straight.some(v=>Math.abs(v.latitude-p(0,0).latitude)>0));console.log('PASS straight GPX corridor');
const elbow=bufferTrack([p(0,0),p(100,0),p(100,100)],15);assert.equal(elbow.length,6);assert.ok(area(elbow)>0);console.log('PASS L-shaped GPX corridor');
const loop=bufferTrack([p(0,0),p(100,0),p(100,100),p(0,100),p(0,0)],15);assert.equal(loop.length,4);assert.ok(area(loop)>0);console.log('PASS closed-loop GPX envelope');
assert.throws(()=>bufferTrack([{latitude:91,longitude:121},p(1,1)],15),/valid latitude.*longitude/);
assert.throws(()=>bufferTrack([p(0,0),p(1,1)],4),/5–50/);
console.log('PASS invalid coordinates and width are rejected');
const dense=Array.from({length:3000},(_,i)=>p(i,20*Math.sin(i/300*Math.PI*2)));
const simplified=simplifyTrack(dense,2);
assert.ok(simplified.points.length<=250,`3000-point GPX simplified to ${simplified.points.length} points`);
assert.ok(simplified.points.length>=2);
assert.ok(simplified.maxDeviationMeters<=2.000001,`maximum deviation ${simplified.maxDeviationMeters} m exceeds configured tolerance`);
assert.ok(simplified.maxDeviationMeters>0);
assert.equal(bufferTrack(simplified.points,15).length,simplified.points.length*2);
console.log(`PASS 3000-point GPX simplified to ${simplified.points.length} points; measured maximum deviation ${simplified.maxDeviationMeters.toFixed(2)} m`);
const closedDense=Array.from({length:3000},(_,i)=>{const a=2*Math.PI*i/2999;return p(100*Math.cos(a),100*Math.sin(a));});
const closedSimplified=simplifyTrack(closedDense,2);
assert.ok(closedSimplified.points.length<=250);
assert.ok(closedSimplified.points.length>=4);
assert.equal(closedSimplified.points[0].latitude,closedSimplified.points.at(-1).latitude);
assert.equal(closedSimplified.points[0].longitude,closedSimplified.points.at(-1).longitude);
assert.ok(closedSimplified.maxDeviationMeters<=2.000001);
assert.ok(bufferTrack(closedSimplified.points,15).length<=500);
console.log('PASS 3000-point closed GPX simplifies, retains closure, and stays under polygon vertex limit');
assert.ok(editor.includes('TrailGeometry.simplifyTrack(track,tolerance)')&&editor.includes('measured maximum deviation')&&editor.includes('simplified.length>250'));
assert.ok(editorPage.includes('id="gpx-tolerance"')&&editorPage.includes('min="5" max="50"'));
console.log('PASS GPX editor exposes configurable simplification, deviation/point-count preview, and preserves 5–50 m corridor limits');
